"""Generate FRConfig.java from the original RelicsConfigHandler.

Every option keeps the original name, category, default, range and comment, so values from an old
ForgottenRelics.cfg translate 1:1. Run: python -I tools/gen_config.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "reference/original/src/main/java/com/integral/forgottenrelics/handlers/RelicsConfigHandler.java"
OUT = ROOT / "src/main/java/com/integral/forgottenrelics/FRConfig.java"

CALL = re.compile(
    r'this\.(\w+)\s*=\s*config\.get(Float|Boolean|Int)\(\s*"(\w+)"\s*,\s*"([^"]+)"\s*,\s*([^,]+?)\s*,'
    r'(?:\s*([^,"]+?)\s*,\s*([^,"]+?)\s*,)?\s*"((?:[^"\\]|\\.)*)"\s*\)\s*;', re.S)


def java_num(v, kind):
    v = v.strip()
    if "POSITIVE_INFINITY" in v:
        return "Double.MAX_VALUE"
    if kind == "Int":
        return v
    return v.rstrip("Ff") if not v.endswith("D") else v[:-1]


def main():
    text = SRC.read_text(encoding="utf-8")
    opts = []
    for m in CALL.finditer(text):
        field, kind, name, cat, default, lo, hi, comment = m.groups()
        opts.append(dict(field=field, kind=kind, name=name, cat=cat, default=default, lo=lo, hi=hi,
                         comment=comment.replace("\\\"", "'")))
    cats = []
    for o in opts:
        if o["cat"] not in cats:
            cats.append(o["cat"])

    lines = [
        "package com.integral.forgottenrelics;",
        "",
        "import net.neoforged.neoforge.common.ModConfigSpec;",
        "",
        "/**",
        " * Common config. Generated by tools/gen_config.py from the original RelicsConfigHandler: same option names,",
        " * categories, defaults and ranges, so an old ForgottenRelics.cfg maps 1:1. Do not edit by hand.",
        " */",
        "public final class FRConfig {",
        "    public static final ModConfigSpec SPEC;",
        "",
    ]
    for o in opts:
        t = {"Float": "ModConfigSpec.DoubleValue", "Int": "ModConfigSpec.IntValue",
             "Boolean": "ModConfigSpec.BooleanValue"}[o["kind"]]
        lines.append(f"    public static final {t} {o['field']};")
    lines += ["", "    static {", "        ModConfigSpec.Builder b = new ModConfigSpec.Builder();"]
    for cat in cats:
        key = cat.lower().replace(" ", "_")
        lines.append(f'        b.push("{key}");')
        for o in (x for x in opts if x["cat"] == cat):
            comment = o["comment"].replace('"', "'")
            if o["kind"] == "Boolean":
                expr = f'b.comment("{comment}").define("{o["name"]}", {o["default"].strip()})'
            elif o["kind"] == "Int":
                expr = (f'b.comment("{comment}").defineInRange("{o["name"]}", {o["default"].strip()}, '
                        f'{o["lo"].strip()}, {o["hi"].strip()})')
            else:
                expr = (f'b.comment("{comment}").defineInRange("{o["name"]}", {java_num(o["default"], "Float")}, '
                        f'{java_num(o["lo"], "Float")}, {java_num(o["hi"], "Float")})')
            lines.append(f"        {o['field']} = {expr};")
        lines.append("        b.pop();")
    lines += ["        SPEC = b.build();", "    }", "", "    private FRConfig() {", "    }", "}", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(opts)} options in {len(cats)} categories -> {OUT.relative_to(ROOT)}")
    declared = len(re.findall(r"public static (?:float|boolean|int) \w+;", text))
    if declared != len(opts):
        print(f"WARNING: {declared} fields declared, {len(opts)} parsed")


if __name__ == "__main__":
    main()
